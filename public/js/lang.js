// Export for the node verification script (no-op in browsers).
if (typeof module !== 'undefined' && module.exports) { module.exports = LANG_DICT; }

(function () {
  if (typeof PK === 'undefined') return; // app.js must load first
  PK.lang = {
    get() {
      try { return localStorage.getItem('porikkha_lang') || 'bn'; } catch (e) { return 'bn'; }
    },
    set(l) {
      try { localStorage.setItem('porikkha_lang', l); } catch (e) {}
      location.reload();
    },
    t(key) {
      const L = PK.lang.get();
      return (LANG_DICT[L] && LANG_DICT[L][key]) || LANG_DICT.bn[key] || key;
    },
  };
  function applyI18n() {
    const t = PK.lang.t;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    document.documentElement.lang = PK.lang.get();
  }
  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', applyI18n);
    else applyI18n();
  }
})();
